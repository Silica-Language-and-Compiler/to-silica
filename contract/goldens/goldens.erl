%% ------------------------------------------------------------------ write

wire(Term) -> B = term_to_binary(Term), <<(byte_size(B)):32/big, B/binary>>.

write([DirArg]) ->
    Dir = to_list(DirArg),
    Index = [begin
                 ok = file:write_file(filename:join(Dir, Name ++ ".frames"), [wire(F) || F <- Frames]),
                 ok = file:write_file(filename:join(Dir, Name ++ ".expect"), [io_lib:format("~0p.~n", [E]) || E <- Expect]),
                 io_lib:format("~s\t~b frames\t~s~n", [Name, length(Frames), What])
             end || {Name, What, Frames, Expect} <- sessions()],
    ok = file:write_file(filename:join(Dir, "INDEX.txt"), Index),
    io:format("wrote ~b goldens into ~s~n", [length(Index), Dir]),
    halt(0).

%% ------------------------------------------------------------------ play

play([PortArg, DirArg]) ->
    Port = list_to_integer(to_list(PortArg)),
    Dir = to_list(DirArg),
    Names = lists:sort([filename:basename(F, ".frames") || F <- filelib:wildcard(filename:join(Dir, "*.frames"))]),
    Bad = [N || N <- Names, not play_one(Port, Dir, N)],
    io:format("~b goldens, ~b failed~n", [length(Names), length(Bad)]),
    halt(case Bad of [] -> 0; _ -> 1 end).

play_one(Port, Dir, Name) ->
    {ok, Bytes} = file:read_file(filename:join(Dir, Name ++ ".frames")),
    {ok, Want} = file:consult(filename:join(Dir, Name ++ ".expect")),
    Got = try run(Port, split(Bytes)) catch C:R -> [{crashed, C, R}] end,
    case Got =:= Want of
        true -> io:format("ok    ~s~n", [Name]), true;
        false -> io:format("FAIL  ~s~n      want ~0p~n      got  ~0p~n", [Name, Want, Got]), false
    end.

split(<<Len:32/big, Etf:Len/binary, Rest/binary>>) -> [Etf | split(Rest)];
split(<<>>) -> [].

%% Plays one connection: the first frame, then the others under the credit the welcome and (:credit, n) give.
run(Port, [First | Rest]) ->
    {ok, S} = gen_tcp:connect("127.0.0.1", Port, [binary, {packet, 4}, {active, false}]),
    ok = gen_tcp:send(S, First),
    R = case recv(S) of
            {welcome, #{flow := #{credit := Credit} = Flow}} -> [{welcome, Flow} | go(S, Rest, Credit, [])];
            Other -> [reduce(Other)]
        end,
    gen_tcp:close(S),
    R.

go(S, [], _Credit, Acc) -> finish(S, Acc);
go(S, Frames, 0, Acc) ->
    case recv(S) of
        {credit, N} -> go(S, Frames, N, Acc);
        Stop when Stop =:= closed; Stop =:= timeout -> lists:reverse([Stop | Acc]);
        Other -> go(S, Frames, 0, [reduce(Other) | Acc])
    end;
go(S, [F | Rest], Credit, Acc) ->
    ok = gen_tcp:send(S, F),
    go(S, Rest, Credit - 1, Acc).

finish(S, Acc) ->
    case recv(S) of
        {credit, _} -> finish(S, Acc);
        {result, _} = R -> lists:reverse([reduce(R) | Acc]);
        Stop when Stop =:= closed; Stop =:= timeout -> lists:reverse([Stop | Acc]);
        Other -> finish(S, [reduce(Other) | Acc])
    end.

recv(S) ->
    case gen_tcp:recv(S, 0, 3000) of
        {ok, Bin} -> binary_to_term(Bin);
        {error, closed} -> closed;
        {error, timeout} -> timeout
    end.

reduce({refused, #{reason := R}}) -> {refused, R};
reduce({rejected, #{seq := Seq, reason := R}}) -> {rejected, Seq, R};
reduce({diagnostic, #{seq := Seq, finding := #{code := Code}}}) -> {diagnostic, Seq, Code};
reduce({result, #{status := St, counts := C, files := F}}) -> {result, St, C, F};
reduce({released, #{freed := F}}) -> {released, F};
reduce(Other) -> Other.

to_list(A) when is_atom(A) -> atom_to_list(A);
to_list(L) -> L.
