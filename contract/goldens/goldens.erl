%% goldens: the golden sessions of the to-silica TCP transport contract, version 1 (contract T11.1).
%%
%% A golden is one connection's worth of sender frames and the replies a transpiler must give:
%%   <name>.frames   the bytes a sender writes, frame after frame: <<Length:32/big, Etf/binary>> each (contract T4.1),
%%                   Etf as term_to_binary/1 writes it. The first frame is the connection's first (a hello in
%%                   check mode, or a release); the rest are sent under credit (T6.2).
%%   <name>.expect   the replies, one Erlang term per line, reduced to what the contract fixes:
%%                     {welcome, Flow}                       the session id is the transpiler's to choose
%%                     {refused, Reason}                     detail is text for people
%%                     {rejected, Seq, Reason}               where is text for people
%%                     {diagnostic, Seq, Code}
%%                     {result, Status, Counts, Files}
%%                     {released, Freed}   closed            (closed: the transpiler closed with no result)
%%                   (:credit, n) frames are not listed: when they come is the transpiler's business.
%%
%% Every golden is a check-mode session (contract 6.5) or needs no session, so playing them stores nothing.
%% The .frames and .expect files are generated by write/1 from the terms below and are kept in the repository;
%% a sender in any language can replay the .frames bytes, and a transpiler is checked with play/1.
%%
%%   erl -noshell -pa <ebin> -s goldens write <dir>            regenerate the files
%%   erl -noshell -pa <ebin> -s goldens play <port> <dir>      play every golden against a transpiler; status 0 if all match
%% Needs add_example (contract/examples) compiled into <ebin>.
-module(goldens).
-export([write/1, play/1, sessions/0]).

%% ------------------------------------------------------------------ frames

hello() -> hello(fun(H) -> H end).
hello(Change) ->
    {hello, H} = hd(add_example:frames()),
    O = maps:get(options, H),
    {hello, Change(H#{options := O#{run := #{mode => check, max_frame => 1048576}}})}.

silica_hello() ->
    hello(fun(H) ->
        O = maps:get(options, H),
        H#{options := O#{profile := silica,
                         choices := [C || C = #{requirement := R} <- maps:get(choices, O), R =:= a3_4 orelse R =:= a6_8],
                         hints := #{proven => trust, declared => check, inferred => check}}}
    end).

ub(Seq, Name, Silica) ->
    {unit_begin, #{seq => Seq, unit_name => Name, silica_unit => Silica, source => <<Name/binary, ".src">>}}.
ue(Seq, Name, Forms) -> {unit_end, #{seq => Seq, unit_name => Name, forms => Forms}}.
fin(Seq, Units) -> {'end', #{seq => Seq, units => Units}}.

function(Seq, Unit, Nodes, Types, Hints) ->
    {form, #{seq => Seq, unit_name => Unit,
             body => {function, #{head => #{name => <<"f">>, arity => 0, exported => true, file => <<"g.src">>},
                                  code => #{locations => [{1, 1}], nodes => Nodes, clauses => [length(Nodes) - 1]},
                                  types => Types,
                                  notes => #{hints => Hints, overrides => []}}}}}.
function(Seq, Unit, Nodes) -> function(Seq, Unit, Nodes, [], []).

add_form(Seq) ->
    {form, F} = lists:nth(3, add_example:frames()),
    {form, F#{seq := Seq}}.

type_form(Seq, Unit) ->
    {form, #{seq => Seq, unit_name => Unit,
             body => {type, #{head => #{name => <<"pair">>, params => [<<"a">>], exported => true, file => <<"g.src">>},
                              at_line => 3, types => all_types(), root => length(all_types()) - 1}}}}.

%% Contract 8.6. A declared type, sent before the form that names it (T8.14):
%%     -record(point, {x :: float(), y :: float()}).
types_point_form(Seq, Unit) ->
    {form, #{seq => Seq, unit_name => Unit,
             body => {type, #{head => #{name => <<"demo_point">>, params => [], exported => true, file => <<"demo.erl">>},
                              at_line => 2, types => [{t_float, f64}, {t_record, [{<<"x">>, 0}, {<<"y">>, 0}]}], root => 1}}}}.

%% A function whose every type is stated by the sender (T8.10) and whose conversions are operators (T8.12):
%%     -spec ratio(integer(), integer(), #point{}) -> float().
%%     ratio(A, B, P) -> S = scale(A), case B == 0 of true -> 0.0; false -> (S / float(B)) + P#point.x end.
%% The binding S is hinted (node 3), so is the call it is bound to (node 5); B is converted with to_float; the
%% divisor is guarded by the sender (T8.15).
typed_function(Seq, Unit) ->
    Nodes = [{var, 0, <<"A">>}, {var, 0, <<"B">>}, {var, 0, <<"P">>},                      % 0 1 2  the patterns
             {var, 1, <<"S">>}, {var, 1, <<"A">>}, {call, 1, <<>>, <<"scale">>, [4]},       % 3 4 5
             {match, 1, 3, 5},                                                              % 6      S = scale(A)
             {var, 2, <<"B">>}, {int, 2, 0}, {op, 2, <<"==">>, [7, 8]},                      % 7 8 9  B == 0
             {boolean, 2, true}, {float, 2, <<"0.0">>}, {clause, 2, [10], -1, 11},          % 10 11 12
             {boolean, 3, false}, {var, 3, <<"S">>}, {var, 3, <<"B">>},                     % 13 14 15
             {op, 3, <<"to_float">>, [15]}, {op, 3, <<"/">>, [14, 16]},                      % 16 17  S / to_float(B)
             {var, 3, <<"P">>}, {field, 3, 18, <<"x">>}, {op, 3, <<"+">>, [17, 19]},         % 18 19 20
             {clause, 3, [13], -1, 20}, {'case', 2, 9, [12, 21]},                           % 21 22
             {block, 1, [6, 22]}, {clause, 0, [0, 1, 2], -1, 23}],                          % 23 24
    Types = [{t_int, i64}, {t_float, f64}, {t_named, <<"demo_point">>, []}, {t_fun, [0, 0, 2], 1}],
    Hint = fun(Node, Type, Strength) -> #{node => Node, type => Type, strength => Strength, policy => default} end,
    {form, #{seq => Seq, unit_name => Unit,
             body => {function, #{head => #{name => <<"ratio">>, arity => 3, exported => true, file => <<"demo.erl">>},
                                  code => #{locations => [{4, 1}, {4, 19}, {5, 5}, {5, 40}], nodes => Nodes, clauses => [24]},
                                  types => Types,
                                  notes => #{hints => [Hint(-1, 3, declared), Hint(3, 1, inferred), Hint(5, 1, declared)],
                                             overrides => []}}}}}.

entry_form(Seq, Unit) -> {form, #{seq => Seq, unit_name => Unit, body => {entry, #{function => <<"f">>, arity => 0}}}}.

