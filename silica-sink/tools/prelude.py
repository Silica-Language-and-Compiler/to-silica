#!/usr/bin/env python3
"""prelude.py: writes ts_prelude.silica, the unit that makes separate compiler runs agree on atoms and shapes.

The Silica compiler numbers atoms and record shapes in the order it first meets them, per run (silica.atoms,
silica.shapes). silica-sink/build.sh compiles the transpiler in several runs (the compiler cannot hold all of it in
one, STATUS.md "Compiler memory"), and objects of different runs link correctly only when the runs give every atom
and every shape the same number. So every run compiles this unit before the transpiler's own units: it names every
atom and every record shape that any unit of the build names, in one fixed order, and each run's tables are then
the same. build.sh checks that they are and fails if not (an atom or shape this scan missed).

The scan is textual: an atom is `:name`; a shape is the list of field names of a `{ name: ..., name: ... }` record
type or literal. Naming too many (a `:word` in a comment) is harmless. The atoms the compiler's derived decoders
add on their own are listed here by hand (DERIVED).

Usage: python3 prelude.py [--all] <output file> <unit.silica>...      (the units in the order the build lists them)
"""
import re
import sys

ATOM = re.compile(r"(?<![A-Za-z0-9_:)\]])(:[A-Za-z_][A-Za-z0-9_]*)")
# Atoms the compiler's derived decoders bring in themselves (transport design 4.3), which no source names.
DERIVED = [":truncated", ":trailing_bytes", ":bad_tag", ":too_large", ":too_deep", ":too_long", ":out_of_range",
           ":bad_utf8", ":unknown_atom", ":bad_variant", ":missing_field", ":duplicate_field", ":unknown_field",
           ":unsupported", ":bad_version", ":some", ":none", ":rejected"]
# Atoms the runtime's supervisors bring in. They are named after every scanned atom, and only in a prelude for the
# whole build (--all), so that the schema run's prelude, and with it the cached schema object, does not change.
LATE = [":sink_set", ":removed", ":terminated", ":not_found", ":duplicate_child_id", ":child_started"]
FIELD = re.compile(r"\s*([a-z_][A-Za-z0-9_]*)\s*:(?!:)")


def shapes_of(text):
    # String literals and comments are taken out in one pass, in the order they stand: a string may hold "//" (the
    # printer's texts do) and a comment may hold a quote.
    text = re.sub(r'"(?:\\.|[^"\\])*"|//[^\n]*', lambda m: '""' if m.group(0).startswith('"') else "", text)
    found = []
    stack = []
    for i, ch in enumerate(text):
        if ch == "{":
            stack.append(i)
        elif ch == "}" and stack:
            start = stack.pop()
            inner = text[start + 1:i]
            depth = 0
            items = [""]
            plain = True
            for j, c in enumerate(inner):
                if c in "([{":
                    depth += 1
                elif c in ")]}":
                    depth -= 1
                if depth == 0 and (c == ";" or inner[j:j + 2] in ("<-", "->")):
                    plain = False
                    break
                if c == "," and depth == 0:
                    items.append("")
                else:
                    items[-1] += c
            if not plain:
                continue
            names = []
            for item in items:
                m = FIELD.match(item)
                if not m:
                    names = []
                    break
                names.append(m.group(1))
            if names and len(set(names)) == len(names):
                found.append(tuple(names))
    return found


def main():
    args = [a for a in sys.argv[1:] if a != "--all"]
    out, units = args[0], args[1:]
    atoms, shapes = list(DERIVED), []
    for unit in units:
        text = open(unit).read()
        for a in ATOM.findall(re.sub(r'"(?:\\.|[^"\\])*"', '""', text)):
            if a not in atoms:
                atoms.append(a)
        for s in shapes_of(text):
            if s not in shapes:
                shapes.append(s)
    if "--all" in sys.argv:
        atoms += [a for a in LATE if a not in atoms]
    lines = ["// GENERATED by silica-sink/tools/prelude.py: every atom and record shape of the build, in one order.",
             "module ts_prelude;", ""]
    chunks = [atoms[i:i + 200] for i in range(0, len(atoms), 200)]
    for k in range(len(chunks)):
        lines.append("export atoms_%d/1;" % k)
    for k in range(len(shapes)):
        lines.append("export shape_%d/0;" % k)
    lines.append("")
    for k, chunk in enumerate(chunks):
        lines.append("fn atoms_%d(i: int64) -> atom {\n    case i of {" % k)
        lines += ["        %d -> %s;" % (i, a) for i, a in enumerate(chunk)]
        lines.append("        _: int64 -> :ok\n    }\n}\n")
    for k, names in enumerate(shapes):
        lines.append("fn shape_%d() -> { %s } {\n    { %s }\n}\n" % (
            k, ", ".join("%s: int64" % n for n in names), ", ".join("%s: 0" % n for n in names)))
    open(out, "w").write("\n".join(lines))
    print("prelude: %d atoms, %d shapes" % (len(atoms), len(shapes)))


if __name__ == "__main__":
    main()
